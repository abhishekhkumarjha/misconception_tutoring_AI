export type MathTopic =
  | 'Linear Equations'
  | 'Algebra'
  | 'Quadratic Equations'
  | 'Fractions & Decimals'
  | 'Order of Operations'
  | 'Word Problems'
  | 'Geometry'
  | 'Number'
  | 'Rounding and Estimating'
  | 'Data and Statistics'
  | string;

export type DifficultyLevel = 'Easy' | 'Medium' | 'Hard';

/**
 * Three-tier canonical problem level used across RAG retrieval,
 * tutor response calibration, and UI display.
 * Beginner  = Easy / introductory
 * Intermediate = Medium / standard
 * Advanced  = Hard / competition / multi-step
 */
export type ProblemLevel = 'Beginner' | 'Intermediate' | 'Advanced';

export type ErrorType =
  | 'none'
  | 'arithmetic'
  | 'sign_error'
  | 'order_of_operations'
  | 'distributive_property'
  | 'combining_like_terms'
  | 'inverted_operation'
  | 'incomplete_step'
  | 'conceptual_misconception'
  | 'other';

export type SubjectType = 'math' | 'python' | 'cross_domain';

export interface MathProblem {
  id: string;
  title: string;
  topic: MathTopic;
  difficulty: DifficultyLevel;
  /** Canonical three-tier level derived from difficulty. Drives RAG retrieval & tutor language. */
  level?: ProblemLevel;
  /** Subject category: math, python programming, or cross-domain */
  subjectType?: SubjectType;
  problem: string;
  targetSolution: string;
  stepByStepSolution: string[];
  hints: string[];
  options?: { [key: string]: string };
  correctOption?: string;
  starterCode?: string;
  expectedOutput?: string;
  testCases?: Array<{ input?: string; expected: string; description?: string }>;
  subjectHierarchy?: {
    subject?: string;
    topic?: string;
    subtopic?: string;
  };
  source?: 'eedi_dq' | 'mathdial' | 'gsm8k' | 'hendrycks' | 'custom' | 'miscon_ai' | 'cross_domain';
  commonMisconceptions?: {
    attemptExample: string;
    errorType: ErrorType;
    explanation: string;
  }[];
}

export interface SolutionAnalysis {
  isCorrect: boolean;
  isFinalAnswer: boolean;
  errorType: ErrorType | string;
  errorSummary: string;
  mistakeStep?: string | null;
  studentRationale: string;
  severity: 'none' | 'minor' | 'conceptual' | 'critical' | 'moderate';
  /** Mental execution trace generated by Enhanced Model */
  trace?: string;
  /** False-positive and correctness verification check */
  verification?: string;
  /** Reference taxonomy candidates considered */
  candidatesConsidered?: string[];
  /** Captured runtime sandbox output */
  outputCaptured?: string;
  /** Runtime error if execution terminated prematurely */
  runtimeError?: string | null;
  /** True if systematic misconception was identified */
  misconceptionFound?: boolean;
}

export interface PedagogicalDecision {
  strategy:
    | 'socratic_question'
    | 'step_clarification'
    | 'conceptual_analogy'
    | 'error_reflection'
    | 'affirmation_next_step'
    | 'final_celebration'
    | 'press_for_accuracy'
    | 'press_for_reasoning'
    | 'revoicing'
    | 'keep_together'
    | 'concept_relation'
    | 'restating'
    | string;
  hintLevel: 1 | 2 | 3;
  answerRevealed: boolean;
  pedagogicalGoal: string;
  nextRecommendedPrompt?: string;
  talkMove?: string;
}

export interface EvaluationMetrics {
  errorDetectionAccuracy: number; // 0 to 100
  hintQualityScore: number;       // 0 to 100
  pedagogicalEffectiveness: number; // 0 to 100
  socraticRuleAdhered: boolean;   // true if tutor avoided leaking direct answer
  latencyMs?: number;
  exemplarsUsed?: string[];
}

export interface TutorResponse {
  id: string;
  message: string;
  guidingQuestion?: string;
  encouragement: string;
  analysis: SolutionAnalysis;
  pedagogical: PedagogicalDecision;
  evaluation: EvaluationMetrics;
}

export interface ChatMessage {
  id: string;
  sender: 'student' | 'tutor' | 'system';
  text: string;
  timestamp: number;
  attemptType?: 'step' | 'final';
  codeSnippet?: string;
  subjectType?: SubjectType;
  analysis?: SolutionAnalysis;
  pedagogical?: PedagogicalDecision;
  evaluation?: EvaluationMetrics;
  isLatest?: boolean;
}

export interface SessionData {
  problem: MathProblem;
  messages: ChatMessage[];
  attemptsCount: number;
  errorsDetectedCount: number;
  isSolved: boolean;
}
